export type Hand = "R" | "L";
export type NoteOrnament = "none" | "flam" | "drag" | "ruff" | "diddle" | "buzz";
export type RudimentCategory =
  | "warmup"
  | "rolls"
  | "diddles"
  | "flams"
  | "drags"
  | "hybrid";
export type Difficulty = 1 | 2 | 3 | 4 | 5;

export interface RudimentNote {
  hand: Hand;
  accent?: boolean;
  ghost?: boolean;
  ornament?: NoteOrnament;
  /** Relative step weight within the subdivision grid (default 1, e.g. 0.5 for 32nd pairs inside a 16th grid) */
  duration?: number;
}

export interface Rudiment {
  id: string;
  name: string;
  category: RudimentCategory;
  difficulty: Difficulty;
  timeSignature: [number, number];
  /** Notes per quarter-note beat (e.g., 2 = 8ths, 3 = 8th triplets, 4 = 16ths, 6 = sextuplets) */
  subdivision: 2 | 3 | 4 | 6;
  defaultBpm: number;
  targetBpm: number;
  description: string;
  notes: RudimentNote[];
}

const n = (
  hand: Hand,
  opts?: {
    a?: boolean;
    g?: boolean;
    o?: NoteOrnament;
    d?: number;
  },
): RudimentNote => ({
  hand,
  accent: opts?.a ?? false,
  ghost: opts?.g ?? false,
  ornament: opts?.o ?? "none",
  duration: opts?.d ?? 1,
});

