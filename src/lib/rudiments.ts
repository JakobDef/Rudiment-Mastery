export function noteDuration(note: RudimentNote): number {
  return note.duration ?? 1;
}

export function patternDurationUnits(rudiment: Rudiment): number {
  return rudiment.notes.reduce((sum, note) => sum + noteDuration(note), 0);
}

export function patternQuarterBeats(rudiment: Rudiment): number {
  return patternDurationUnits(rudiment) / rudiment.subdivision;
}

export function quarterNotesPerBar(rudiment: Rudiment): number {
  const [beats, division] = rudiment.timeSignature;
  return beats * (4 / division);
}

export function hasPositiveDurations(rudiment: Rudiment): boolean {
  return rudiment.notes.every((note) => {
    const duration = noteDuration(note);
    return Number.isFinite(duration) && duration > 0;
  });
}

export function hasCompleteBeats(rudiment: Rudiment): boolean {
  const beats = patternQuarterBeats(rudiment);
  return Number.isFinite(beats) && beats > 0 && Math.abs(beats - Math.round(beats)) < 1e-6;
}

export function hasValidSticking(rudiment: Rudiment): boolean {
  return (
    rudiment.notes.length > 0 &&
    rudiment.notes.every((note) => note.hand === "R" || note.hand === "L")
  );
}

export function getRudimentById(id: string): Rudiment | undefined {
  return RUDIMENTS_DB.find((rudiment) => rudiment.id === id);
}

export function filterRudiments(input: {
  category: RudimentCategory | "all";
  difficulty: Difficulty | "all";
  query: string;
}): readonly Rudiment[] {
  const query = input.query.trim().toLowerCase();
  return RUDIMENTS_DB.filter((rudiment) => {
    if (input.category !== "all" && rudiment.category !== input.category) return false;
    if (input.difficulty !== "all" && rudiment.difficulty !== input.difficulty) return false;
    if (!query) return true;
    const haystack = `${rudiment.name} ${rudiment.description} ${rudiment.id}`.toLowerCase();
    return haystack.includes(query);
  });
}
